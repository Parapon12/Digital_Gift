def font(run, size=16, bold=False):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:eastAsia"), FONT)


def p(
    doc,
    text="",
    *,
    size=16,
    bold=False,
    align="left",
    before=0,
    after=6,
    first=0,
    left=0,
):
    para = doc.add_paragraph()
    pf = para.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = 1.5
    if first:
        pf.first_line_indent = Cm(first)
    if left:
        pf.left_indent = Cm(left)
    para.alignment = {
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
        "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
    }.get(align, WD_ALIGN_PARAGRAPH.LEFT)
    if text:
        font(para.add_run(text), size=size, bold=bold)
    return para


def h1(doc, text):
    return p(doc, text, size=18, bold=True, before=16, after=8)


def h2(doc, text):
    return p(doc, text, size=16, bold=True, before=12, after=6)


def body(doc, text):
    return p(doc, text, align="justify", first=1.0, after=8)


def num(doc, items):
    for i, t in enumerate(items, 1):
        p(doc, f"{i}) {t}", align="justify", left=0.75, after=3)


def dash(doc, items):
    for t in items:
        p(doc, f"- {t}", align="justify", left=0.75, after=3)


def br(doc):
    doc.add_page_break()


def caption(doc, text):
    """ชื่อตาราง/ภาพ วางเหนือตาราง"""
    return p(doc, text, size=14, bold=True, align="center", before=10, after=4)


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        para = cell.paragraphs[0]
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        font(para.add_run(h), size=13, bold=True)
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = t.rows[r + 1].cells[c]
            cell.text = ""
            font(cell.paragraphs[0].add_run(str(val)), size=12)
    p(doc, "", after=8)
    return t


def fig(doc, no, title, hint=""):
    p(doc, "", after=2)
    p(doc, f"[วาง{no}ตรงนี้]", size=13, bold=True, align="center", after=2)
    p(doc, f"{no}  {title}", size=13, bold=True, align="center", after=2)
    if hint:
        p(doc, hint, size=12, align="center", after=8)


def margins(doc):
    for s in doc.sections:
        s.top_margin = Cm(2.54)
        s.bottom_margin = Cm(2.54)
        s.left_margin = Cm(3.0)
        s.right_margin = Cm(2.5)


